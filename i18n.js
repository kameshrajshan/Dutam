  window.DUTAM_I18N = { en: en, nl: nl, de: de, fr: fr };

  window.DutamI18n = {
    STORAGE_KEY: "dutam-lang",
    supported: ["en", "nl", "de", "fr"],
    labels: {
      en: "English",
      nl: "Dutch",
      de: "German",
      fr: "French",
    },

    getLang: function () {
      try {
        var stored = localStorage.getItem(this.STORAGE_KEY);
        if (stored && this.supported.indexOf(stored) !== -1) return stored;
      } catch (e) {}
      return "en";
    },

    setLang: function (lang) {
      var next = this.supported.indexOf(lang) !== -1 ? lang : "en";
      try {
        localStorage.setItem(this.STORAGE_KEY, next);
      } catch (e) {}
      return next;
    },

    t: function (key, lang) {
      var l = lang || this.getLang();
      if (this.supported.indexOf(l) === -1) l = "en";
      var dict = window.DUTAM_I18N[l] || window.DUTAM_I18N.en;
      if (dict && typeof dict[key] === "string") return dict[key];
      var enDict = window.DUTAM_I18N.en;
      if (enDict && typeof enDict[key] === "string") return enDict[key];
      return key;
    },

    apply: function (lang) {
      var l = lang != null ? this.setLang(lang) : this.getLang();
      if (this.supported.indexOf(l) === -1) l = "en";

      document.documentElement.lang = l;

      var nodes = document.querySelectorAll("[data-i18n]");
      for (var i = 0; i < nodes.length; i++) {
        var el = nodes[i];
        if (el.tagName === "META") continue;
        var key = el.getAttribute("data-i18n");
        if (key) el.textContent = this.t(key, l);
      }

      var htmlNodes = document.querySelectorAll("[data-i18n-html]");
      for (var h = 0; h < htmlNodes.length; h++) {
        var htmlEl = htmlNodes[h];
        var htmlKey = htmlEl.getAttribute("data-i18n-html");
        if (htmlKey) htmlEl.innerHTML = this.t(htmlKey, l);
      }

      var phNodes = document.querySelectorAll("[data-i18n-placeholder]");
      for (var p = 0; p < phNodes.length; p++) {
        var phEl = phNodes[p];
        var phKey = phEl.getAttribute("data-i18n-placeholder");
        if (phKey) phEl.setAttribute("placeholder", this.t(phKey, l));
      }

      var ariaNodes = document.querySelectorAll("[data-i18n-aria]");
      for (var a = 0; a < ariaNodes.length; a++) {
        var ariaEl = ariaNodes[a];
        var ariaKey = ariaEl.getAttribute("data-i18n-aria");
        if (ariaKey) ariaEl.setAttribute("aria-label", this.t(ariaKey, l));
      }

      var altNodes = document.querySelectorAll("[data-i18n-alt]");
      for (var t = 0; t < altNodes.length; t++) {
        var altEl = altNodes[t];
        var altKey = altEl.getAttribute("data-i18n-alt");
        if (altKey) altEl.setAttribute("alt", this.t(altKey, l));
      }

      var titleNodes = document.querySelectorAll("[data-i18n-title]");
      for (var ti = 0; ti < titleNodes.length; ti++) {
        var titleKey = titleNodes[ti].getAttribute("data-i18n-title");
        if (titleKey) document.title = this.t(titleKey, l);
      }

      var metaNodes = document.querySelectorAll(
        'meta[data-i18n-meta="description"]'
      );
      for (var m = 0; m < metaNodes.length; m++) {
        var metaEl = metaNodes[m];
        var metaKey = metaEl.getAttribute("data-i18n");
        if (metaKey) metaEl.setAttribute("content", this.t(metaKey, l));
      }

      var labelNodes = document.querySelectorAll("[data-language-label]");
      for (var lb = 0; lb < labelNodes.length; lb++) {
        labelNodes[lb].textContent = this.labels[l] || this.labels.en;
      }

      try {
        document.dispatchEvent(
          new CustomEvent("dutam:langchange", { detail: { lang: l } })
        );
      } catch (e) {
        var evt = document.createEvent("CustomEvent");
        evt.initCustomEvent("dutam:langchange", false, false, { lang: l });
        document.dispatchEvent(evt);
      }

      return l;
    },
  };
